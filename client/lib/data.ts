interface TierInput {
  starter: number;
  pro: number;
  enterprise: number;
  starterFeatures: string[];
  proFeatures: string[];
  enterpriseFeatures: string[];
  proBadge?: string;
}

function makeTiers(input: TierInput): PricingTier[] {
  const annual = (monthly: number) => Math.round(monthly * 0.8);
  return [
    {
      name: "Starter",
      description: "For focused teams tracking a small set of rivals.",
      monthly: input.starter,
      annualMonthly: annual(input.starter),
      features: input.starterFeatures,
    },
    {
      name: "Pro",
      description: "For teams that need a complete view of the market.",
      monthly: input.pro,
      annualMonthly: annual(input.pro),
      features: input.proFeatures,
      highlighted: true,
      badge: input.proBadge ?? "Most popular",
    },
    {
      name: "Enterprise",
      description: "For global organizations with complex requirements.",
      monthly: input.enterprise,
      annualMonthly: annual(input.enterprise),
      features: input.enterpriseFeatures,
    },
  ];
}

