interface TierInput {
  value: number;
  mainstream: number;
  premium: number;
  valueFeatures: string[];
  mainstreamFeatures: string[];
  premiumFeatures: string[];
  mainstreamBadge?: string;
}

function makeTiers(input: TierInput): PricingTier[] {
  const festive = (mrp: number) => Math.round((mrp * 0.9) / 10) * 10;
  return [
    {
      name: "Value",
      description: "Everyday audio, accessories, and entry smartphones.",
      monthly: input.value,
      annualMonthly: festive(input.value),
      features: input.valueFeatures,
    },
    {
      name: "Mainstream",
      description: "Popular TVs, laptops, and premium smartphones.",
      monthly: input.mainstream,
      annualMonthly: festive(input.mainstream),
      features: input.mainstreamFeatures,
      highlighted: true,
      badge: input.mainstreamBadge ?? "Festive pick",
    },
    {
      name: "Premium",
      description: "Flagship TVs, appliances, and large-format displays.",
      monthly: input.premium,
      annualMonthly: festive(input.premium),
      features: input.premiumFeatures,
    },
  ];
}

